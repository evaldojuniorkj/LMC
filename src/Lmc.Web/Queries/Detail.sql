SELECT e.ID_LMCENTRADATANQUES AS Id, e.ID_PRODUTOS AS ProductId,
       COALESCE(RTRIM(p.NOMEPRODUTO), 'Produto sem cadastro') AS Product,
       e.ID_TANQUES AS TankId, COALESCE(NULLIF(RTRIM(t.CODIGOTANQUE), ''), CONVERT(varchar(10), e.ID_TANQUES)) AS Tank,
       CONVERT(decimal(19, 4), e.QTDE) AS Volume,
       CONVERT(char(10), e.DTACONTA, 23) AS OperationalDate,
       CONVERT(varchar(30), e.DATAREPL, 126) AS ReplicationDate, e.SELOFISCAL AS FiscalSeal
FROM dbo.LMCENTRADATANQUES e
LEFT JOIN dbo.PRODUTOS p ON p.ID_FILIAL=e.ID_FILIAL AND p.ID_PRODUTOS=e.ID_PRODUTOS
LEFT JOIN dbo.TANQUES t ON t.ID_FILIAL=e.ID_FILIAL AND t.ID_TANQUES=e.ID_TANQUES
WHERE e.ID_FILIAL=@branch AND e.ID_DB=@db AND e.ID_COMPROVANTE=@id
ORDER BY e.ID_LMCENTRADATANQUES;

SELECT ID_MOVPRODUTOS AS Id, ID_TURNOS AS ShiftId,
       CONVERT(char(10), DTACONTA, 23) AS OperationalDate,
       CONVERT(varchar(30), DATAREPL, 126) AS ReplicationDate
FROM dbo.MOVPRODUTOS
WHERE ID_FILIAL=@branch AND ID_DB=@db AND ID_COMPROVANTE=@id
ORDER BY ID_MOVPRODUTOS;

SELECT t.ID_TANQUES TankId,t.ID_PRODUTOS ProductId,
       COALESCE(NULLIF(RTRIM(t.CODIGOTANQUE),''),CONVERT(varchar(10),t.ID_TANQUES)) Tank,
       CONVERT(bit,CASE WHEN t.ATIVO=1 THEN 1 ELSE 0 END) Active,
       CONVERT(char(10),t.DATAATIVACAO,23) ActivatedAt
FROM dbo.TANQUES t WHERE t.ID_FILIAL=@branch AND EXISTS (
 SELECT 1 FROM dbo.LMCENTRADATANQUES e WHERE e.ID_FILIAL=@branch AND e.ID_DB=@db
 AND e.ID_COMPROVANTE=@id AND e.ID_PRODUTOS=t.ID_PRODUTOS)
ORDER BY t.ID_PRODUTOS,t.ID_TANQUES;
