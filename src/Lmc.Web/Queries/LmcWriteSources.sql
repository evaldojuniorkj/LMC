-- Somente leitura. Executada na mesma transação da conferência/gravação.
SELECT l.ID_LMC Id,l.ID_PRODUTOS ProductId,CONVERT(char(10),l.DTACONTA,23) Date,l.NROCONTROLE Number,
 CONVERT(decimal(19,4),l.VLRVENDASDIA) SalesValue,CONVERT(decimal(19,4),l.VLRACUMULADO) AccumulatedValue,
 CONVERT(varchar(30),l.HORALMC,126) CreatedAt,CONVERT(varchar(max),l.OBS) Observation,
 CONVERT(varchar(30),l.DATAREPL,126) ReplicatedAt
FROM dbo.LMC l WITH(UPDLOCK,HOLDLOCK)
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product ORDER BY l.DTACONTA,l.ID_LMC;

SELECT b.ID_LMCBICOS Id,b.ID_LMC BookId,b.ID_BICOS PumpId,b.ID_TANQUES TankId,
 CONVERT(decimal(19,4),b.ENCERRANTEABERTURA) Opening,CONVERT(decimal(19,4),b.ENCERRANTEFECHAMENTO) Closing,
 CONVERT(decimal(19,4),b.AFERICAO) Calibration,CONVERT(decimal(19,4),b.PPL) Price,CONVERT(decimal(19,4),b.VENDAS) Sales
FROM dbo.LMCBICOS b JOIN dbo.LMC l ON l.ID_FILIAL=b.ID_FILIAL AND l.ID_LMC=b.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product AND l.DTACONTA>=DATEADD(day,-1,@date) AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY b.ID_LMC,b.ID_LMCBICOS;

SELECT t.ID_LMCTANQUES Id,t.ID_LMC BookId,t.ID_TANQUES TankId,CONVERT(decimal(19,4),t.QTDETANQUE) Opening,
 CONVERT(decimal(19,4),t.QTDECONCILIACAO) Closing
FROM dbo.LMCTANQUES t JOIN dbo.LMC l ON l.ID_FILIAL=t.ID_FILIAL AND l.ID_LMC=t.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product AND l.DTACONTA>=DATEADD(day,-1,@date) AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY t.ID_LMC,t.ID_LMCTANQUES;

SELECT r.ID_LMCCOMPROVANTES Id,r.ID_LMC BookId,r.ID_TANQUES TankId,r.NROCOMPROVANTE Number,
 CONVERT(decimal(19,4),r.VOLUMERECEBIDO) Volume,CONVERT(char(10),r.DTAENTRADA,23) DocumentDate,RTRIM(r.CNPJ_FORNECEDOR) SupplierTaxId
FROM dbo.LMCCOMPROVANTES r JOIN dbo.LMC l ON l.ID_FILIAL=r.ID_FILIAL AND l.ID_LMC=r.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY r.ID_LMCCOMPROVANTES;

SELECT b.ID_BICOS PumpId,b.ID_TANQUES TankId,CONVERT(bit,t.ATIVO) TankActive,CONVERT(char(10),b.DATAATIVACAO,23) ActivatedAt
FROM dbo.BICOS b JOIN dbo.TANQUES t ON t.ID_FILIAL=b.ID_FILIAL AND t.ID_TANQUES=b.ID_TANQUES
WHERE b.ID_FILIAL=@branch AND t.ID_PRODUTOS=@product ORDER BY b.ID_BICOS;

SELECT e.ID_ENCERRANTESTURNOS Id,e.ID_BICOS PumpId,t.ID_TURNOS ShiftId,CONVERT(int,t.TURNO) ShiftNumber,
 CONVERT(decimal(19,4),e.ENCERRANTEABERTURA) Opening,CONVERT(decimal(19,4),e.ENCERRANTEFECHAMENTO) Closing,
 CONVERT(decimal(19,4),e.AFERICAO) Calibration,CONVERT(decimal(19,4),e.PPL) Price
FROM dbo.ENCERRANTESTURNOS e JOIN dbo.TURNOS t ON t.ID_FILIAL=e.ID_FILIAL AND t.ID_TURNOS=e.ID_TURNOS
WHERE e.ID_FILIAL=@branch AND t.DATATURNO>=@date AND t.DATATURNO<DATEADD(day,1,@date) AND t.TURNO<>0
ORDER BY e.ID_BICOS,t.TURNO,e.ID_ENCERRANTESTURNOS;

SELECT e.ID_LMCENTRADATANQUES ParcelId,RTRIM(s.CNPJCPF) SupplierTaxId
FROM dbo.LMCENTRADATANQUES e
JOIN dbo.COMPROVANTES c ON c.ID_FILIAL=e.ID_FILIAL AND c.ID_DB=e.ID_DB AND c.ID_COMPROVANTE=e.ID_COMPROVANTE
LEFT JOIN dbo.ENTIDADES s ON s.ID_FILIAL=c.ID_FILIAL AND s.ID_ENTIDADE=c.ID_ENTIDADE
WHERE e.ID_FILIAL=@branch AND e.ID_PRODUTOS=@product AND e.DTACONTA>=@date AND e.DTACONTA<DATEADD(day,1,@date)
ORDER BY e.ID_LMCENTRADATANQUES;

SELECT w.ID_LMC FROM dbo.LMC_WS_VINCULADO w JOIN dbo.LMC l ON l.ID_FILIAL=w.ID_FILIAL AND l.ID_LMC=w.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product AND l.DTACONTA>=@date
ORDER BY w.ID_LMC;

SELECT COUNT(*) ConfigCount,MIN(CONVERT(int,USARNROSEQ)) Sequential,MIN(CONVERT(int,NUMERACAOUNICA)) SingleNumber,
 MIN(CONVERT(int,TIPONUMERACAO)) NumberType,MIN(CONVERT(int,PAGINALMC)) FirstPage FROM dbo.CFGLMC;

SELECT ISNULL(SUM(b.VENDAS),0) MonthSales FROM dbo.LMCBICOS b JOIN dbo.LMC l ON l.ID_FILIAL=b.ID_FILIAL AND l.ID_LMC=b.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.ID_PRODUTOS=@product AND l.DTACONTA>=DATEADD(day,1-DAY(@date),@date) AND l.DTACONTA<@date;
