-- Conferência somente leitura. As datas das medições são preservadas.
SELECT l.ID_LMC Id,l.ID_PRODUTOS ProductId,COALESCE(RTRIM(p.NOMEPRODUTO),'Produto sem cadastro') Product,
 CONVERT(char(10),l.DTACONTA,23) Date,l.NROCONTROLE Number
FROM dbo.LMC l LEFT JOIN dbo.PRODUTOS p ON p.ID_FILIAL=l.ID_FILIAL AND p.ID_PRODUTOS=l.ID_PRODUTOS
WHERE l.ID_FILIAL=@branch AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY l.ID_LMC;

WITH tanks AS (
 SELECT l.ID_PRODUTOS ProductId,t.ID_TANQUES TankId,l.ID_LMC BookId,t.QTDETANQUE LegacyOpening,t.QTDECONCILIACAO LegacyClosing
 FROM dbo.LMC l JOIN dbo.LMCTANQUES t ON t.ID_FILIAL=l.ID_FILIAL AND t.ID_LMC=l.ID_LMC
 WHERE l.ID_FILIAL=@branch AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date)
 UNION ALL
 SELECT t.ID_PRODUTOS,t.ID_TANQUES,NULL,NULL,NULL FROM dbo.TANQUES t
 WHERE t.ID_FILIAL=@branch AND t.ATIVO=1 AND (t.DATAATIVACAO IS NULL OR t.DATAATIVACAO<DATEADD(day,1,@date))
 AND NOT EXISTS(SELECT 1 FROM dbo.LMC l JOIN dbo.LMCTANQUES x ON x.ID_FILIAL=l.ID_FILIAL AND x.ID_LMC=l.ID_LMC
 WHERE l.ID_FILIAL=t.ID_FILIAL AND x.ID_TANQUES=t.ID_TANQUES AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date))
)
SELECT x.ProductId,COALESCE(RTRIM(p.NOMEPRODUTO),'Produto sem cadastro') Product,x.TankId,x.BookId,
 CONVERT(decimal(19,4),t.CAPACIDADE) Capacity,CONVERT(decimal(19,4),x.LegacyOpening) LegacyOpening,
 CONVERT(decimal(19,4),x.LegacyClosing) LegacyClosing
FROM tanks x LEFT JOIN dbo.TANQUES t ON t.ID_FILIAL=@branch AND t.ID_TANQUES=x.TankId
LEFT JOIN dbo.PRODUTOS p ON p.ID_FILIAL=@branch AND p.ID_PRODUTOS=x.ProductId ORDER BY x.ProductId,x.TankId,x.BookId;

SELECT l.ID_PRODUTOS ProductId,b.ID_BICOS PumpId,b.ID_TANQUES TankId,l.ID_LMC BookId,
 CONVERT(decimal(19,4),b.ENCERRANTEABERTURA) Opening,CONVERT(decimal(19,4),b.ENCERRANTEFECHAMENTO) Closing,
 CONVERT(decimal(19,4),b.AFERICAO) Calibration,CONVERT(decimal(19,4),b.VENDAS) Sales
FROM dbo.LMC l JOIN dbo.LMCBICOS b ON b.ID_FILIAL=l.ID_FILIAL AND b.ID_LMC=l.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY l.ID_LMC,b.ID_LMCBICOS;

WITH events AS (
 SELECT ID_BICOS,DATA,ENCERRANTE,ENCERRANTEANTERIOR,
 DENSE_RANK() OVER(PARTITION BY ID_BICOS ORDER BY DATA) FirstRank,
 DENSE_RANK() OVER(PARTITION BY ID_BICOS ORDER BY DATA DESC) LastRank
 FROM dbo.CONSOLEARQUIVO WHERE ID_FILIAL=@branch AND DATA>=@date AND DATA<DATEADD(day,1,@date)
), archive AS (
 SELECT ID_BICOS,COUNT(*) Events,MIN(DATA) FirstAt,MAX(DATA) LastAt,
 MIN(CASE WHEN FirstRank=1 THEN ENCERRANTEANTERIOR END) Opening,
 MIN(CASE WHEN LastRank=1 THEN ENCERRANTE END) Closing,
 CASE WHEN COUNT(DISTINCT CASE WHEN FirstRank=1 THEN ENCERRANTEANTERIOR END)>1
 OR COUNT(DISTINCT CASE WHEN LastRank=1 THEN ENCERRANTE END)>1
 OR SUM(CASE WHEN FirstRank=1 AND ENCERRANTEANTERIOR IS NULL OR LastRank=1 AND ENCERRANTE IS NULL THEN 1 ELSE 0 END)>0 THEN 1 ELSE 0 END Ambiguous
 FROM events GROUP BY ID_BICOS
)
SELECT a.ID_BICOS PumpId,b.ID_TANQUES TankId,t.ID_PRODUTOS ProductId,a.Events,
 CONVERT(varchar(19),a.FirstAt,126) FirstAt,CONVERT(varchar(19),a.LastAt,126) LastAt,
 CONVERT(decimal(19,4),a.Opening) Opening,CONVERT(decimal(19,4),a.Closing) Closing,CONVERT(bit,a.Ambiguous) Ambiguous,
 STUFF((SELECT DISTINCT ','+CONVERT(varchar(40),CONVERT(decimal(19,4),e.ENCERRANTE)) FROM events e
 WHERE e.ID_BICOS=a.ID_BICOS AND e.LastRank=1 AND e.ENCERRANTE IS NOT NULL FOR XML PATH('')),1,1,'') ClosingCandidates
FROM archive a LEFT JOIN dbo.BICOS b ON b.ID_FILIAL=@branch AND b.ID_BICOS=a.ID_BICOS
LEFT JOIN dbo.TANQUES t ON t.ID_FILIAL=@branch AND t.ID_TANQUES=b.ID_TANQUES
ORDER BY a.ID_BICOS;

SELECT e.ID_LMCENTRADATANQUES Id,e.ID_PRODUTOS ProductId,e.ID_TANQUES TankId,e.ID_DB DatabaseId,e.ID_COMPROVANTE DocumentId,
 c.NROCOMPROVANTE Number,COALESCE(RTRIM(s.NOMEENTIDADE),RTRIM(s.RAZAOSOCIALENTIDADE),'Sem fornecedor') Supplier,
 CONVERT(char(10),c.DATA,23) DocumentDate,CONVERT(char(10),c.DTAEMISSAO,23) EntryDate,
 CONVERT(char(10),c.DTACONTA,23) OperationalDate,CONVERT(char(10),e.DTACONTA,23) ParcelDate,
 CONVERT(decimal(19,4),e.QTDE) Volume,CONVERT(bit,ISNULL(c.CANCELADO,0)) Canceled,
 CONVERT(bit,CASE WHEN c.SAIDAS_ENTRADAS=1 AND c.CANCELADO=0 AND c.DTACONTA>=@date AND c.DTACONTA<DATEADD(day,1,@date)
 AND e.DTACONTA>=@date AND e.DTACONTA<DATEADD(day,1,@date) AND e.QTDE>=0 AND c.ID_TURNOS IS NOT NULL
 AND EXISTS(SELECT 1 FROM dbo.TURNOS t WHERE t.ID_FILIAL=c.ID_FILIAL AND t.ID_TURNOS=c.ID_TURNOS
   AND (t.TURNO=0 OR CONVERT(date,t.DATATURNO)=CONVERT(date,c.DTACONTA)))
 AND EXISTS(SELECT 1 FROM dbo.MOVPRODUTOS m WHERE m.ID_FILIAL=c.ID_FILIAL AND m.ID_DB=c.ID_DB AND m.ID_COMPROVANTE=c.ID_COMPROVANTE)
 AND NOT EXISTS(SELECT 1 FROM dbo.MOVPRODUTOS m WHERE m.ID_FILIAL=c.ID_FILIAL AND m.ID_DB=c.ID_DB AND m.ID_COMPROVANTE=c.ID_COMPROVANTE
 AND (m.DTACONTA IS NULL OR CONVERT(date,m.DTACONTA)<>CONVERT(date,c.DTACONTA) OR m.ID_TURNOS IS NULL OR m.ID_TURNOS<>c.ID_TURNOS))
 THEN 1 ELSE 0 END) Usable
FROM dbo.LMCENTRADATANQUES e
LEFT JOIN dbo.COMPROVANTES c ON c.ID_FILIAL=e.ID_FILIAL AND c.ID_DB=e.ID_DB AND c.ID_COMPROVANTE=e.ID_COMPROVANTE
LEFT JOIN dbo.ENTIDADES s ON s.ID_FILIAL=c.ID_FILIAL AND s.ID_ENTIDADE=c.ID_ENTIDADE
WHERE e.ID_FILIAL=@branch AND ((e.DTACONTA>=@date AND e.DTACONTA<DATEADD(day,1,@date)) OR (c.DTACONTA>=@date AND c.DTACONTA<DATEADD(day,1,@date)))
ORDER BY c.NROCOMPROVANTE,e.ID_LMCENTRADATANQUES;

SELECT l.ID_PRODUTOS ProductId,c.ID_LMC BookId,c.ID_TANQUES TankId,c.NROCOMPROVANTE Number,
 CONVERT(decimal(19,4),c.VOLUMERECEBIDO) Volume,CONVERT(char(10),c.DTAENTRADA,23) Date
FROM dbo.LMC l JOIN dbo.LMCCOMPROVANTES c ON c.ID_FILIAL=l.ID_FILIAL AND c.ID_LMC=l.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.DTACONTA>=@date AND l.DTACONTA<DATEADD(day,1,@date)
ORDER BY l.ID_LMC,c.ID_LMCCOMPROVANTES;

-- Valida dentro do CASE antes da conversão: leituras legadas podem exceder decimal.
-- Compatível com nível 100, sem TRY_CONVERT e sem alterar os dados originais.
SELECT 'MOVTANQUES' Source,ID_MOVTANQUES Id,ID_TANQUES TankId,CONVERT(varchar(19),DTACONTA,126) At,
 CONVERT(decimal(19,4),CASE WHEN LEITURA BETWEEN 0 AND 1000000000 THEN LEITURA END) Volume,
 CONVERT(varchar(50),CASE WHEN LEITURA BETWEEN 0 AND 1000000000 THEN NULL ELSE LEITURA END,2) InvalidVolume
FROM dbo.MOVTANQUES WHERE ID_FILIAL=@branch AND ABERTURA=0 AND DTACONTA>=DATEADD(day,-1,@date) AND DTACONTA<DATEADD(day,2,@date)
UNION ALL
SELECT 'ESTOQUETANQUELMC',ID_ESTOQUETANQUESLMC,ID_TANQUES,CONVERT(varchar(19),DTACONTA,126),
 CONVERT(decimal(19,4),CASE WHEN QTDETANQUE BETWEEN 0 AND 1000000000 THEN QTDETANQUE END),
 CONVERT(varchar(50),CASE WHEN QTDETANQUE BETWEEN 0 AND 1000000000 THEN NULL ELSE QTDETANQUE END,2)
FROM dbo.ESTOQUETANQUELMC WHERE ID_FILIAL=@branch AND DTACONTA>=DATEADD(day,-1,@date) AND DTACONTA<DATEADD(day,2,@date)
UNION ALL
SELECT 'LEITURASTANQUES',CONVERT(int,ID_LEITURASTANQUES),ID_TANQUES,CONVERT(varchar(19),DATA,126),
 CONVERT(decimal(19,4),CASE WHEN QTDELIDA BETWEEN 0 AND 1000000000 THEN QTDELIDA END),
 CONVERT(varchar(50),CASE WHEN QTDELIDA BETWEEN 0 AND 1000000000 THEN NULL ELSE QTDELIDA END,2)
FROM dbo.LEITURASTANQUES WHERE ID_FILIAL=@branch AND DATA>=DATEADD(day,-1,@date) AND DATA<DATEADD(day,2,@date);
