-- Somente leitura dos livros e detalhes salvos da filial, sem fontes de automação.
SELECT l.ID_LMC,l.ID_PRODUTOS,COALESCE(RTRIM(p.NOMEPRODUTO),'Produto '+CONVERT(varchar(12),l.ID_PRODUTOS)),CONVERT(date,l.DTACONTA)
FROM dbo.LMC l LEFT JOIN dbo.PRODUTOS p ON p.ID_FILIAL=l.ID_FILIAL AND p.ID_PRODUTOS=l.ID_PRODUTOS
WHERE l.ID_FILIAL=@branch AND l.DTACONTA IS NOT NULL
ORDER BY l.ID_PRODUTOS,l.DTACONTA,l.ID_LMC;

SELECT t.ID_LMC,'tank' Kind,t.ID_TANQUES,CONVERT(decimal(19,4),t.QTDETANQUE) Opening,CONVERT(decimal(19,4),t.QTDECONCILIACAO) Closing,
    receipts.Volume,sales.Volume
FROM dbo.LMCTANQUES t JOIN dbo.LMC l ON l.ID_FILIAL=t.ID_FILIAL AND l.ID_LMC=t.ID_LMC
OUTER APPLY(SELECT CASE WHEN COUNT(*)=COUNT(VOLUMERECEBIDO) THEN COALESCE(SUM(CONVERT(decimal(19,4),VOLUMERECEBIDO)),0) END Volume
    FROM dbo.LMCCOMPROVANTES c WHERE c.ID_FILIAL=t.ID_FILIAL AND c.ID_LMC=t.ID_LMC AND c.ID_TANQUES=t.ID_TANQUES) receipts
OUTER APPLY(SELECT CASE WHEN COUNT(*)=COUNT(VENDAS) THEN COALESCE(SUM(CONVERT(decimal(19,4),VENDAS)),0) END Volume
    FROM dbo.LMCBICOS b WHERE b.ID_FILIAL=t.ID_FILIAL AND b.ID_LMC=t.ID_LMC AND b.ID_TANQUES=t.ID_TANQUES) sales
WHERE l.ID_FILIAL=@branch AND l.DTACONTA IS NOT NULL
UNION ALL
SELECT b.ID_LMC,'pump',b.ID_BICOS,CONVERT(decimal(19,4),b.ENCERRANTEABERTURA),CONVERT(decimal(19,4),b.ENCERRANTEFECHAMENTO),NULL,NULL
FROM dbo.LMCBICOS b JOIN dbo.LMC l ON l.ID_FILIAL=b.ID_FILIAL AND l.ID_LMC=b.ID_LMC
WHERE l.ID_FILIAL=@branch AND l.DTACONTA IS NOT NULL;
