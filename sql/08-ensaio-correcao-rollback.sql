-- ENSAIO DE DESENVOLVIMENTO: executa UPDATE e sempre ROLLBACK.
-- Nao executar em producao. Nao cria nem altera objetos do banco.
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;
DECLARE @Filial smallint=17581, @Db smallint=17581, @Documento int=560835;
DECLARE @Destino smalldatetime='20260930', @Turno int=8960;
DECLARE @Antes nvarchar(max), @Depois nvarchar(max), @LMCAntes nvarchar(max), @LMCDepois nvarchar(max);
IF DB_NAME()<>'ATXDADOS' THROW 50001,'Ensaio restrito a copia ATXDADOS identificada no projeto.',1;
IF NOT EXISTS(SELECT 1 FROM dbo.COMPROVANTES WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento AND NROCOMPROVANTE=1349380 AND DTACONTA='20260929' AND ID_TURNOS=1)
    THROW 50002,'O caso de referencia mudou. Nao executar automaticamente.',1;
IF NOT EXISTS(SELECT 1 FROM dbo.TURNOS WHERE ID_FILIAL=@Filial AND ID_TURNOS=@Turno AND DATATURNO=@Destino)
    THROW 50003,'Destino do ensaio nao localizado.',1;
BEGIN TRY
    BEGIN TRANSACTION;
    SELECT @Antes=(SELECT c.* FROM dbo.COMPROVANTES c WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento FOR XML RAW, BINARY BASE64);
    SELECT @LMCAntes=(SELECT l.* FROM dbo.LMC l WHERE ID_FILIAL=@Filial ORDER BY ID_LMC FOR XML RAW, BINARY BASE64);
    UPDATE dbo.COMPROVANTES SET DTACONTA=@Destino,ID_TURNOS=@Turno
    WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento;
    SELECT 'apos_cabecalho' AS Etapa,c.DTACONTA AS DiaNota,c.ID_TURNOS AS TurnoNota,m.DTACONTA AS DiaMovimento,m.ID_TURNOS AS TurnoMovimento,e.DTACONTA AS DiaTanque,e.QTDE
    FROM dbo.COMPROVANTES c JOIN dbo.MOVPRODUTOS m ON m.ID_FILIAL=c.ID_FILIAL AND m.ID_DB=c.ID_DB AND m.ID_COMPROVANTE=c.ID_COMPROVANTE
    JOIN dbo.LMCENTRADATANQUES e ON e.ID_FILIAL=c.ID_FILIAL AND e.ID_DB=c.ID_DB AND e.ID_COMPROVANTE=c.ID_COMPROVANTE
    WHERE c.ID_FILIAL=@Filial AND c.ID_DB=@Db AND c.ID_COMPROVANTE=@Documento;
    UPDATE dbo.MOVPRODUTOS SET DTACONTA=@Destino,ID_TURNOS=@Turno
    WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento
      AND (DTACONTA<>@Destino OR ID_TURNOS<>@Turno);
    UPDATE dbo.LMCENTRADATANQUES SET DTACONTA=@Destino
    WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento AND DTACONTA<>@Destino;
    SELECT 'apos_conjunto' AS Etapa,c.DATA,c.DTAEMISSAO,c.DTACONTA AS DiaNota,c.ID_TURNOS AS TurnoNota,m.DTACONTA AS DiaMovimento,m.ID_TURNOS AS TurnoMovimento,e.DTACONTA AS DiaTanque,e.QTDE
    FROM dbo.COMPROVANTES c JOIN dbo.MOVPRODUTOS m ON m.ID_FILIAL=c.ID_FILIAL AND m.ID_DB=c.ID_DB AND m.ID_COMPROVANTE=c.ID_COMPROVANTE
    JOIN dbo.LMCENTRADATANQUES e ON e.ID_FILIAL=c.ID_FILIAL AND e.ID_DB=c.ID_DB AND e.ID_COMPROVANTE=c.ID_COMPROVANTE
    WHERE c.ID_FILIAL=@Filial AND c.ID_DB=@Db AND c.ID_COMPROVANTE=@Documento;
    SELECT @LMCDepois=(SELECT l.* FROM dbo.LMC l WHERE ID_FILIAL=@Filial ORDER BY ID_LMC FOR XML RAW, BINARY BASE64);
    SELECT CASE WHEN @LMCAntes=@LMCDepois THEN 1 ELSE 0 END AS CabecalhosLMCInalterados;
    ROLLBACK TRANSACTION;
    SELECT @Depois=(SELECT c.* FROM dbo.COMPROVANTES c WHERE ID_FILIAL=@Filial AND ID_DB=@Db AND ID_COMPROVANTE=@Documento FOR XML RAW, BINARY BASE64);
    IF @Antes<>@Depois THROW 50004,'Cabecalho divergente apos rollback.',1;
    SELECT 'rollback_concluido' AS Etapa,c.DTACONTA,c.ID_TURNOS,m.DTACONTA AS DiaMovimento,m.ID_TURNOS AS TurnoMovimento,e.DTACONTA AS DiaTanque,e.QTDE
    FROM dbo.COMPROVANTES c JOIN dbo.MOVPRODUTOS m ON m.ID_FILIAL=c.ID_FILIAL AND m.ID_DB=c.ID_DB AND m.ID_COMPROVANTE=c.ID_COMPROVANTE
    JOIN dbo.LMCENTRADATANQUES e ON e.ID_FILIAL=c.ID_FILIAL AND e.ID_DB=c.ID_DB AND e.ID_COMPROVANTE=c.ID_COMPROVANTE
    WHERE c.ID_FILIAL=@Filial AND c.ID_DB=@Db AND c.ID_COMPROVANTE=@Documento;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
